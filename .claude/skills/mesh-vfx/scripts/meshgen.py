"""Mesh VFX generator (pure Python + numpy): the same shapes the Blender script builds, but runnable anywhere and tested.
Shapes: crescent slash, shell (outer aura + inverted inner), shockwave cone, twisted vortex, faceted debris.
Every mesh gets straightened grid UVs (the 'Follow Active Quads' result: u along the length, v across), a 3% UV inset,
and a per-vertex mask colour. Writes OBJ (+ .json stats).  1 unit = 1 stud.

  python3 meshgen.py crescent out.obj --bend 210 --radius 4 --width 1.2
  python3 meshgen.py shockwave out.obj ; vortex ; debris --seed 3
"""
import argparse, json, math, sys
import numpy as np

INSET = 0.03  # keep UVs 3% off the 0..1 borders so bilinear filtering never wraps a seam

def uv_inset(u, v):
    return INSET + u * (1 - 2 * INSET), INSET + v * (1 - 2 * INSET)

class Mesh:
    def __init__(self):
        self.v, self.uv, self.col, self.f = [], [], [], []
    def add(self, p, uv, c):
        self.v.append(p); self.uv.append(uv); self.col.append(c); return len(self.v) - 1
    def quad(self, a, b, c, d, flip=False):
        if flip: self.f += [(a, c, b), (a, d, c)]
        else: self.f += [(a, b, c), (a, c, d)]
    def tris(self): return len(self.f)
    def normals(self):
        V = np.array(self.v); N = np.zeros_like(V)
        for a, b, c in self.f:
            n = np.cross(V[b] - V[a], V[c] - V[a]); N[a] += n; N[b] += n; N[c] += n
        L = np.linalg.norm(N, axis=1, keepdims=True); L[L == 0] = 1
        return N / L
    def write_obj(self, path, name):
        N = self.normals()
        with open(path, 'w') as fh:
            fh.write(f'# {name} - generated by meshgen.py\no {name}\n')
            for p, c in zip(self.v, self.col):  # vertex colour extension: v x y z r g b
                fh.write(f'v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f} {c:.4f} {c:.4f} {c:.4f}\n')
            for u, v in self.uv: fh.write(f'vt {u:.5f} {v:.5f}\n')
            for n in N: fh.write(f'vn {n[0]:.5f} {n[1]:.5f} {n[2]:.5f}\n')
            for a, b, c in self.f: fh.write(f'f {a+1}/{a+1}/{a+1} {b+1}/{b+1}/{b+1} {c+1}/{c+1}/{c+1}\n')
        V = np.array(self.v); U = np.array(self.uv)
        stats = {'name': name, 'tris': self.tris(), 'verts': len(self.v), 'bounds': [V.min(0).round(3).tolist(), V.max(0).round(3).tolist()],
                 'uv_min': U.min(0).round(4).tolist(), 'uv_max': U.max(0).round(4).tolist()}
        json.dump(stats, open(path.rsplit('.', 1)[0] + '.json', 'w'), indent=1)
        return stats

def crescent(bend=210.0, radius=4.0, width=1.2, length_cuts=16, width_cuts=4, taper_pow=1.8, mask='rim'):
    """Bent, tapered blade arc in the XZ plane (the slash plane). Origin = the arc's centre (the swing pivot).
    mask 'rim': spine black -> rims white (dark core tear); 'core': spine white -> rims black (alpha fade)."""
    m = Mesh(); L, W = length_cuts, width_cuts
    idx = [[0] * (W + 1) for _ in range(L + 1)]
    for i in range(L + 1):
        t = i / L
        a = math.radians(-bend / 2 + bend * t)
        taper = max(0.02, 1 - abs(2 * t - 1) ** taper_pow)  # razor points at both ends
        for j in range(W + 1):
            s = j / W - 0.5
            r = radius + s * width * taper
            edge = abs(2 * s)
            c = edge if mask == 'rim' else 1 - edge
            idx[i][j] = m.add((math.cos(a) * r, 0.0, math.sin(a) * r), uv_inset(t, j / W), c)
    for i in range(L):
        for j in range(W):
            m.quad(idx[i][j], idx[i + 1][j], idx[i + 1][j + 1], idx[i][j + 1])
    return m

def shell(src, offset=0.15, inner=-0.005, both=True):
    """Outer aura shell: the mesh pushed out along its normals, plus (optionally) an inverted copy pulled in by 'inner',
    so overlapping transparent layers sort cleanly instead of z-fighting."""
    N = src.normals(); out = Mesh()
    for k, (p, uv, c) in enumerate(zip(src.v, src.uv, src.col)):
        out.add(tuple(np.array(p) + N[k] * offset), uv, c)
    out.f = list(src.f)
    if both:
        base = len(out.v)
        for k, (p, uv, c) in enumerate(zip(src.v, src.uv, src.col)):
            out.add(tuple(np.array(p) + N[k] * inner), uv, c)
        out.f += [(a + base, c + base, b + base) for a, b, c in src.f]  # flipped winding = inside
    return out

def shockwave(segments=32, loops=4, inner=0.25, outer=2.2, height=0.5, tiles=2):
    """Flat open cone: top ring pinched in, bottom ring flared out. u = around (tiled), v = from centre outward,
    so a vertical-scrolling texture runs radially away from the epicentre."""
    m = Mesh(); idx = []
    for k in range(loops + 1):
        t = k / loops
        r = inner + (outer - inner) * t
        y = height * (1 - t) * 0.1
        row = []
        for s in range(segments + 1):  # duplicate seam column so UVs don't wrap
            a = s / segments * 2 * math.pi
            row.append(m.add((math.cos(a) * r, y, math.sin(a) * r), uv_inset(s / segments, t), 1 - t))
        idx.append(row)
    for k in range(loops):
        for s in range(segments):
            m.quad(idx[k][s], idx[k][s + 1], idx[k + 1][s + 1], idx[k + 1][s], flip=True)
    for i, (u, v) in enumerate(m.uv):  # tile around the ring
        m.uv[i] = (INSET + (u - INSET) * tiles, v)
    return m

def vortex(segments=24, loops=16, height=8.0, r_bottom=1.0, r_top=2.4, twist=270.0, pinch=0.0):
    """Open twisted cylinder (tornado / energy beam). pinch > 0 narrows the middle (hourglass)."""
    m = Mesh(); idx = []
    for k in range(loops + 1):
        t = k / loops
        r = (r_bottom + (r_top - r_bottom) * t) * (1 - pinch * math.sin(math.pi * t))
        tw = math.radians(twist) * t
        row = []
        for s in range(segments + 1):
            a = s / segments * 2 * math.pi + tw
            row.append(m.add((math.cos(a) * r, height * t, math.sin(a) * r), uv_inset(s / segments, t), 1 - abs(2 * t - 1)))
        idx.append(row)
    for k in range(loops):
        for s in range(segments):
            m.quad(idx[k][s], idx[k][s + 1], idx[k + 1][s + 1], idx[k + 1][s])
    return m

def debris(seed=1, size=1.0, jitter=0.45):
    """Faceted rock: icosphere (1 subdivision, 80 tris), vertices pushed along normals at random, flat shaded
    (every face has its own vertices so normals stay hard)."""
    rng = np.random.default_rng(seed)
    p = (1 + 5 ** 0.5) / 2
    V = [(-1, p, 0), (1, p, 0), (-1, -p, 0), (1, -p, 0), (0, -1, p), (0, 1, p), (0, -1, -p), (0, 1, -p), (p, 0, -1), (p, 0, 1), (-p, 0, -1), (-p, 0, 1)]
    F = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
         (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)]
    V = [np.array(v, float) / np.linalg.norm(v) for v in V]
    cache = {}
    def mid(a, b):
        key = (min(a, b), max(a, b))
        if key not in cache:
            v = V[a] + V[b]; V.append(v / np.linalg.norm(v)); cache[key] = len(V) - 1
        return cache[key]
    F2 = []
    for a, b, c in F:
        ab, bc, ca = mid(a, b), mid(b, c), mid(c, a)
        F2 += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
    scale = rng.uniform(1 - jitter, 1 + jitter, len(V)) * np.array([1.0] * len(V))
    stretch = rng.uniform(0.7, 1.3, 3)
    P = [V[i] * scale[i] * stretch * size * 0.5 for i in range(len(V))]
    m = Mesh()
    for a, b, c in F2:  # flat shading: unique verts per face
        ia = m.add(tuple(P[a]), uv_inset(0, 0), 1.0); ib = m.add(tuple(P[b]), uv_inset(1, 0), 1.0); ic = m.add(tuple(P[c]), uv_inset(0.5, 1), 1.0)
        m.f.append((ia, ib, ic))
    return m

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('shape', choices=['crescent', 'shell', 'shockwave', 'vortex', 'debris'])
    ap.add_argument('out'); ap.add_argument('--bend', type=float, default=210); ap.add_argument('--radius', type=float, default=4)
    ap.add_argument('--width', type=float, default=1.2); ap.add_argument('--seed', type=int, default=1); ap.add_argument('--mask', default='rim')
    a = ap.parse_args()
    if a.shape == 'crescent': m = crescent(a.bend, a.radius, a.width, mask=a.mask)
    elif a.shape == 'shell': m = shell(crescent(a.bend, a.radius, a.width, mask='core'))
    elif a.shape == 'shockwave': m = shockwave()
    elif a.shape == 'vortex': m = vortex()
    else: m = debris(a.seed)
    print(json.dumps(m.write_obj(a.out, a.out.rsplit('/', 1)[-1].rsplit('.', 1)[0])))
