"""Generate the material vault: one implementation card per material + a manifest.

    python3 -m tools.celestialrithm.foundry.cards

Writes docs/celestialrithm/frontier/materials/<id>.md, README.md (index) and
materials.json (canonical ids, reproducible config, measured cost when a board
render's JSON exists). Re-run after changing a material; the cards are generated,
so edit materials.py, not the cards.
"""
from __future__ import annotations

import inspect
import json
from pathlib import Path

from . import materials as M

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'docs/celestialrithm/frontier/materials'
BOARDS = [ROOT / 'media/celestialrithm/frontier/board-core12.json', ROOT / 'media/celestialrithm/frontier/board-all16.json']


def measured_cost():
    cost = {}
    for b in BOARDS:
        if b.exists():
            for k, v in json.loads(b.read_text()).get('offline_ms_per_face_python', {}).items():
                cost.setdefault(k, v)
    return cost


def proof(mid):
    """Proof ladder from START_HERE_AND_ACCEPTANCE.md: what this material has actually passed."""
    luau = (ROOT / 'lib/celestialrithm/materials').exists() and any(
        mid.replace('_', '').lower() in p.stem.lower() for p in (ROOT / 'lib/celestialrithm/materials').glob('*.luau'))
    return {'A_math_tests': 'pass (tools/celestialrithm/foundry/test_foundry.py)',
            'B_offline_render': 'pass (board MP4 + JSON, ffprobe-checked)',
            'C_studio_adapter': 'Luau port exists, not run in Studio' if luau else 'not built',
            'D_studio_timing': 'not measured', 'E_viewport_hierarchy_approval': 'not run (needs Studio capture + owner approval)'}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    cost = measured_cost()
    rows, manifest = [], []
    for mid in M.ORDER_12 + M.ORDER_EXTRA:
        cls = M.REGISTRY[mid]; sp = cls.spec()
        src, line = inspect.getsourcelines(cls)
        steps = [s.strip() for s in sp['method'].split('->')]
        c = cost.get(mid)
        entry = {'id': mid, 'name': sp['name'], 'family': sp['family'], 'method_chain': steps, 'palette': sp['palette'],
                 'spec': {k: sp[k] for k in ('geometry', 'optics', 'motion', 'interaction', 'hierarchy', 'rarity', 'bevel', 'ink', 'reduced_motion', 'tiers')},
                 'source': f'tools/celestialrithm/foundry/materials.py:{line}', 'repro': {'seed': 'board --seed N (material i gets N+i)', 'face_px': [241, 112]},
                 'offline_cost_ms_python': c, 'proof': proof(mid)}
        manifest.append(entry)
        sw = ' '.join(f'`{k} {v}`' for k, v in sp['palette'].items())
        md = [f'# {sp["name"]} (`{mid}`)', '', f'**Family:** {sp["family"]} · **Source:** [materials.py:{line}](../../../../tools/celestialrithm/foundry/materials.py) · **Palette:** {sw}', '',
              '## How to recreate it', '']
        md += [f'{i + 1}. {s}' for i, s in enumerate(steps)]
        md += ['', 'Every material then goes through the shared shell (`keycap.compose`): stepped extrusion, black ink, lit bezel, inner glass rim, clearcoat strip and top lip. Faces never move.', '',
               '## Contract', '', '| Field | Value |', '|---|---|']
        for k in ('geometry', 'optics', 'motion', 'interaction', 'hierarchy', 'rarity', 'bevel', 'ink', 'reduced_motion'):
            md.append(f'| {k.replace("_", " ")} | {sp[k]} |')
        md.append(f'| tiers | high: {sp["tiers"]["high"]}; mid: {sp["tiers"]["mid"]}; low: {sp["tiers"]["low"]} |')
        md += ['', '## Measured', '']
        md.append(f'- Offline Python cost per face (241×112): mean {c["mean_ms"]} ms, p95 {c["p95_ms"]} ms. This is NumPy on one CPU core, not Roblox.' if c else '- Offline cost: run a board render to measure.')
        md += ['', '## Proof ladder', '', '| Rung | Status |', '|---|---|'] + [f'| {k} | {v} |' for k, v in entry['proof'].items()]
        md += ['', '## Reproduce', '', '```sh', f'python3 -m tools.celestialrithm.foundry.board --ids {mid} --cols 1 --size 400x260 --seconds 6 --out /tmp/{mid}', '```', '']
        (OUT / f'{mid}.md').write_text('\n'.join(md))
        rows.append(f'| [{sp["name"]}]({mid}.md) | `{mid}` | {sp["family"]} | {steps[0]} | {c["mean_ms"] if c else "—"} |')
    (OUT / 'materials.json').write_text(json.dumps(manifest, indent=1))
    idx = ['# Material vault', '', 'Generated by `python3 -m tools.celestialrithm.foundry.cards` from `tools/celestialrithm/foundry/materials.py`. Edit the material, then regenerate; do not hand-edit cards.', '',
           'Each card is an implementation card: the algorithm chain step by step, the full material contract (palette, bevel, ink, geometry, optics, motion, interaction, hierarchy, tiers, reduced motion, rarity), measured offline cost and the proof-ladder rungs it has passed.', '',
           '| Material | Canonical id | Family | First stage | Offline ms/face |', '|---|---|---|---|---|'] + rows + ['', 'Machine-readable: [materials.json](materials.json).', '']
    (OUT / 'README.md').write_text('\n'.join(idx))
    print(f'{len(manifest)} cards -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
